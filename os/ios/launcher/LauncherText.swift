import Foundation

/// The five languages the games shipped with in their European releases.
/// Anything else falls back to English.
enum LauncherLanguage: String, CaseIterable {
    case english
    case french
    case german
    case italian
    case spanish

    /// The engine's own language codes (LAUNCHER_LANGUAGE_*), in the order the
    /// launcher offers them.
    init(gameLanguage: Int) {
        switch gameLanguage {
        case 1: self = .french
        case 2: self = .german
        case 3: self = .italian
        case 4: self = .spanish
        default: self = .english
        }
    }

    /// The language chosen on the GAME page for the game the app is showing.
    /// The launcher draws its own text in it and the in-game overlay draws the
    /// control labels in it, so one setting governs the launcher, the controls
    /// and the game itself.
    static var selected: LauncherLanguage {
        let defaults = UserDefaults.standard
        let identifier = defaults.string(forKey: "launcher.game") ?? FalloutGame.fallout1.rawValue
        let game = FalloutGame(rawValue: identifier) ?? .fallout1
        let index = defaults.integer(forKey: LauncherModel.optionKey("language", for: game))
        return LauncherLanguage(gameLanguage: index)
    }
}

/// One lookup for every piece of launcher text. Keys are the English strings,
/// so a missing entry simply stays English, and values use the terminology of
/// each game's own localisation (Abri, P.A., Vault and so on).
enum L {
    static func t(_ english: String) -> String {
        let language = LauncherLanguage.selected
        if language == .english {
            return english
        }
        return table[language]?[english] ?? english
    }

    /// Text that comes from the installer, which reports some of its problems
    /// with a file name or a folder in the middle. Those are matched on their
    /// fixed head and tail so the names stay as they are and the sentence
    /// around them is translated. Anything not matched stays as it was sent.
    static func message(_ english: String) -> String {
        let language = LauncherLanguage.selected
        if language == .english {
            return english
        }
        if let exact = table[language]?[english] {
            return exact
        }

        for rule in messageRules {
            let fixed = rule.prefix.count + rule.suffix.count
            guard english.count > fixed,
                  english.hasPrefix(rule.prefix),
                  english.hasSuffix(rule.suffix),
                  let template = rule.templates[language] else {
                continue
            }

            let middle = String(english.dropFirst(rule.prefix.count).dropLast(rule.suffix.count))
            return template.replacingOccurrences(of: "{part}", with: middle)
        }

        return english
    }

